// T-023 device fixture build step (runs in the workspace, before any copy to
// a short filesystem path). Three jobs:
//   1. Vendor @kaicreator/domain-harness (package.json + dist) into vendor/ so
//      the app is self-contained and Metro resolves the package through the
//      "file:vendor/domain-harness" dependency like any registry package.
//   2. Emit fixture-constants.ts with the compiled-package id, computed with
//      the REAL core algorithm (core src) and Node's crypto SHA-256. The
//      device re-validates this id at package load with its own pure-TS
//      SHA-256 — cross-host digest parity is thus proven, not assumed.
//   3. Static E1/E7 gates: the generated Expo store bundle and the vendored
//      core must not reference Node built-ins, better-sqlite3, or the Node
//      host package. Failure here fails the whole build.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { readdirSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const appDir = resolve(dirname(fileURLToPath(import.meta.url)));
const repoRoot = resolve(appDir, '..', '..', '..');
const coreDir = join(repoRoot, 'packages', 'domain-harness');
const vendorDir = join(appDir, 'vendor', 'domain-harness');
const generatedDir = join(appDir, 'generated');

// --- 1. vendor the core package -------------------------------------------
rmSync(vendorDir, { recursive: true, force: true });
mkdirSync(vendorDir, { recursive: true });
cpSync(join(coreDir, 'package.json'), join(vendorDir, 'package.json'));
cpSync(join(coreDir, 'dist'), join(vendorDir, 'dist'), { recursive: true });

// --- 2. fixture constants ---------------------------------------------------
// computeCompiledPackageId is intentionally NOT part of the core public
// barrel; the build step imports it from core src exactly like the T-022
// Node host fixture does. tsx is available at the workspace root.
const manifest = {
  formatVersion: '0.2',
  runtimeContractMajor: 2,
  executionEngineMajor: 2,
  domainId: 'orders',
  domainVersion: '0.3.0-expo-host-test',
  packageId: 'pending',
  targetProfileId: 't023-expo-host@1',
  requiredCapabilities: [],
  workflows: {
    'order-quote': {
      workflowId: 'order-quote',
      definition: {
        initial: 'review',
        states: {
          review: { final: false, done: [], error: [], events: {} },
          approved: { final: true, done: [], error: [], events: {} },
        },
        limits: { maxSteps: 32 },
      },
      messageContracts: {},
    },
  },
  tools: {},
  projections: {},
  schemas: {},
  bindingDigests: {},
};

const computeScript = `
import { computeCompiledPackageId } from '${pathToFileURL(join(coreDir, 'src', 'package', 'index.js')).href}';
const manifest = JSON.parse(process.argv[1]);
const sha256 = { async digestUtf8(value) { return createHash('sha256').update(value, 'utf8').digest('hex'); } };
import { createHash } from 'node:crypto';
console.log(await computeCompiledPackageId(manifest, sha256));
`;
const packageId = execFileSync(
  process.execPath,
  ['--import', 'tsx', '--input-type=module', '--eval', computeScript, JSON.stringify(manifest)],
  { cwd: repoRoot, encoding: 'utf8' },
).trim();
if (!/^[0-9a-f]{64}$/.test(packageId)) {
  throw new Error(`unexpected packageId shape: ${packageId}`);
}

writeFileSync(
  join(appDir, 'fixture-constants.ts'),
  [
    '// GENERATED by build-device-fixture.mjs — do not edit, do not commit.',
    `export const T023_PACKAGE_ID = '${packageId}';`,
    `export const T023_PACKAGE_ID_NODE_SHA256 = '${packageId}';`,
    '',
  ].join('\n'),
);

// --- 3. static E1/E7 gates ---------------------------------------------------
// Scan exactly what the Hermes bundle can reach: all of generated/ (the Expo
// store adapters are imported wholesale) plus the import closure of the
// vendored core barrel (dist/index.js). Legacy Node-bound dist entry points
// (loader/, runner/, persistence/, script/) are NOT reachable from the
// public barrel and are intentionally excluded — the closure walk proves it.
const FORBIDDEN = [
  /better-sqlite3/,
  /@kaicreator\/domain-harness-node/,
  /from\s+['"]node:[a-z]+['"]/,
  /require\(\s*['"]node:[a-z]+['"]\s*\)/,
  /require\(\s*['"](?:fs|crypto|path|os|worker_threads)['"]\s*\)/,
];
const IMPORT_RE = /(?:from|import)\s*\(?\s*['"]([^'"]+)['"]/g;

function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) yield* walk(full);
    else if (full.endsWith('.js')) yield full;
  }
}

function scanFile(file, violations) {
  const text = readFileSync(file, 'utf8');
  for (const pattern of FORBIDDEN) {
    if (pattern.test(text)) violations.push(`${file}: ${pattern}`);
  }
  return text;
}

const violations = [];
let scanned = 0;

if (existsSync(generatedDir)) {
  for (const file of walk(generatedDir)) {
    scanned += 1;
    scanFile(file, violations);
  }
}

// Import closure of the vendored barrel (relative specifiers only; bare
// package specifiers such as xstate/ajv resolve after npm install and are
// followed into node_modules when available).
{
  const require = createRequire(join(appDir, 'package.json'));
  const seen = new Set();
  const queue = [join(vendorDir, 'dist', 'index.js')];
  while (queue.length > 0) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    let text;
    try {
      text = scanFile(file, violations);
    } catch {
      continue;
    }
    scanned += 1;
    for (const match of text.matchAll(IMPORT_RE)) {
      const spec = match[1];
      if (spec.startsWith('.')) {
        queue.push(resolve(dirname(file), spec));
      } else if (!spec.startsWith('node:')) {
        try {
          queue.push(require.resolve(spec, { paths: [appDir, dirname(file)] }));
        } catch {
          // Not yet installed (pre-npm-install run): Metro will hard-fail at
          // bundle time if a reachable specifier cannot resolve on device.
        }
      }
    }
  }
}

if (violations.length > 0) {
  throw new Error(`E1/E7 static gate failed:\n${violations.join('\n')}`);
}

console.log(`T023 device fixture: packageId=${packageId}`);
console.log(`T023 static gates: ${scanned} reachable JS files clean (no Node built-ins / better-sqlite3 / node host package)`);
