/**
 * [KPK-09] Generator for the controlled versioned Kernel Package successor
 * module (kernel-vnext@2.0.0) from the v1 mechanism module.
 *
 * The successor is a REAL complete module file whose only deliberate deltas
 * vs v1 are (documented here and in OWNERSHIP_MAP.md):
 *   1. MODULE_ID → 'kernel-vnext@2.0.0', KERNEL_GENERATION → '2'.
 *   2. Successor header block documenting the version-governed delta.
 *   3. bindGovernance composes ONE additional pinned hard invariant
 *      `inv:gen2-min-10` (forbids event payload amount < 10) into the
 *      baseline semantics, so v1-admitting facts (e.g. amount 5) are denied
 *      under v2 while Business/SDK/Microkernel bytes stay unchanged.
 * Everything else is generated byte-identical from kernel-mechanism-v1.mjs.
 *
 * Run: node src/producer/payload/generate-kernel-v2.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const v1Path = path.join(here, 'kernel-mechanism-v1.mjs');
const v2Path = path.join(here, 'kernel-mechanism-v2.mjs');

const source = await readFile(v1Path, 'utf8');

const SUCCESSOR_HEADER = `/**
 * ============================================================================
 * Kernel Domain Package — vnext v2.0.0 mechanism module (KPK-09 successor)
 * ============================================================================
 *
 * CONTROLLED VERSIONED SUCCESSOR of kernel-mechanism-v1.mjs (same repository,
 * experiment #993). Generated by generate-kernel-v2.mjs; do not hand-edit.
 *
 * Deliberate version-governed deltas vs v1 (and nothing else):
 *   - MODULE_ID 'kernel-vnext@2.0.0', KERNEL_GENERATION '2'.
 *   - The kernel-owned baseline composition adds one extra pinned hard
 *     invariant inv:gen2-min-10 (event payload amount must be >= 10), making
 *     v2 measurably stricter than v1 on the same Business/SDK bytes.
 *   - Journal envelopes and governance pins therefore carry the v2 module
 *     SHA; v1-pinned durable records fail with typed code unavailability
 *     under v2 (no silent cross-version replay) — exercised by KPK-09.
 *
 * All v0.7 migration attributions of kernel-mechanism-v1.mjs apply unchanged.
 */
`;

const deltas = [
  // Replace the v1 header block (first /** ... */ comment) with the successor header.
  [/^\/\*\*[\s\S]*?\*\/\n/, SUCCESSOR_HEADER],
  [/export const MODULE_ID = 'kernel-vnext@1\.1\.0';/, "export const MODULE_ID = 'kernel-vnext@2.0.0';"],
  [/export const KERNEL_GENERATION = '1';/, "export const KERNEL_GENERATION = '2';"],
  [
    // \u0020{N} avoids eslint no-regex-spaces on literal indentation runs.
    new RegExp(
      'const identity = await computeGovernanceBaselineIdentity\\(\\{\\n'
      + '\\u0020{6}domainId: businessEndpoint\\.domainId,\\n'
      + '\\u0020{6}governanceId: `governance:\\$\\{businessEndpoint\\.policyId\\}`,\\n'
      + "\\u0020{6}schemaVersion: '1',\\n"
      + '\\u0020{6}semantics: businessEndpoint\\.governanceSemantics,\\n'
      + '\\u0020{4}\\}, sha256\\);',
    ),
    `const composedSemantics = {
      ...businessEndpoint.governanceSemantics,
      hardInvariants: [
        ...(businessEndpoint.governanceSemantics.hardInvariants ?? []),
        {
          invariantId: 'inv:gen2-min-10',
          predicate: {
            op: 'not',
            predicate: {
              op: 'lt',
              left: { source: 'event', path: ['payload', 'amount'] },
              right: { source: 'literal', value: 10 },
            },
          },
        },
      ],
    };
    const identity = await computeGovernanceBaselineIdentity({
      domainId: businessEndpoint.domainId,
      governanceId: \`governance:\${businessEndpoint.policyId}\`,
      schemaVersion: '1',
      semantics: composedSemantics,
    }, sha256);`,
  ],
  [
    /const body = \{ identity, semantics: businessEndpoint\.governanceSemantics \};/,
    'const body = { identity, semantics: composedSemantics };',
  ],
];

let v2 = source;
for (const [pattern, replacement] of deltas) {
  if (!pattern.test(v2)) {
    throw new Error(`generate-kernel-v2: delta pattern ${pattern} did not match v1 source`);
  }
  v2 = v2.replace(pattern, replacement);
}

await writeFile(v2Path, v2, 'utf8');
console.log(`wrote ${v2Path} (${v2.length} bytes)`);
